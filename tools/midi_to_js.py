#!/usr/bin/env python3
"""Turn a MIDI file into js/music-data.js for the game's little synth.

Usage: python3 tools/midi_to_js.py music/theme.mid
Needs: pip install mido
"""
import json
import sys
from pathlib import Path

import mido

# General MIDI program -> one of the synth's voices.
def voice_for(channel, program):
    if channel == 9:
        return "drums"
    if 32 <= program <= 39:
        return "bass"
    if 56 <= program <= 63:
        return "brass"
    if 24 <= program <= 31:
        return "guitar"
    return "organ"


def drum_kind(note):
    if note in (35, 36):
        return 0  # kick
    if note in (37, 38, 39, 40):
        return 1  # snare
    if note in (49, 52, 55, 57, 51, 53, 59):
        return 3  # cymbal
    return 2      # hi-hat and everything else


def main(src, out):
    mid = mido.MidiFile(src)
    programs = {}
    on = {}
    voices = {}
    t = 0.0
    # Walk with real time (mido handles the tempo map when iterating the file).
    for msg in mid:
        t += msg.time
        if msg.type == "program_change":
            programs[msg.channel] = msg.program
        elif msg.type == "note_on" and msg.velocity > 0:
            on[(msg.channel, msg.note)] = (t, msg.velocity)
        elif msg.type in ("note_off", "note_on"):
            start = on.pop((msg.channel, msg.note), None)
            if not start:
                continue
            t0, vel = start
            v = voice_for(msg.channel, programs.get(msg.channel, 0))
            note = drum_kind(msg.note) if v == "drums" else msg.note
            voices.setdefault(v, []).extend([
                round(t0 * 100), max(1, round((t - t0) * 100)), note, vel
            ])
    data = {"length": round(mid.length, 2), "voices": voices}
    js = ("/* Generated by tools/midi_to_js.py from " + Path(src).name +
          ". Each voice is a flat list of [start, length (both in 1/100 s), note, velocity]. */\n"
          "window.ER = window.ER || {};\nER.MUSIC_DATA = " + json.dumps(data, separators=(",", ":")) + ";\n")
    Path(out).write_text(js)
    print(out, len(js), "bytes", {k: len(v) // 4 for k, v in voices.items()})


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "music/theme.mid",
         sys.argv[2] if len(sys.argv) > 2 else "js/music-data.js")
